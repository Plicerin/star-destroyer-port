/** The seven rows of a character's glyph, or the blank. */
export function glyph(ch) {
  const c = ch.charCodeAt(0);
  const i = (c >= 0x20 && c < 0x60) ? c - 0x20 : 0;
  return GLYPHS.slice(i * 7, i * 7 + 7);
}

/**
 * Paint text rows into an RGBA buffer.
 *
 * @param {Uint8Array} mem the 64K image
 * @param {ImageData} out 280 x 192, the same surface the hi-res page uses
 * @param {object} opts `base` the text page, `fromRow`/`toRow` which rows to draw,
 *   `colour` the foreground, `flashOn` whether flashing characters are currently lit
 */
export function paintText(mem, out, { base = 0x400, fromRow = 0, toRow = ROWS,
  colour = [0xFF, 0xFF, 0xFF], flashOn = true } = {}) {
  const px = out.data;
  const W = out.width ?? 280;
  for (let r = fromRow; r < toRow; r++) {
    const line = base + OFFSETS[r];
    for (let c = 0; c < COLS; c++) {
      const { style, ch } = decode(mem[line + c]);
      const g = glyph(ch);
      const inverse = style === 'inverse' || (style === 'flash' && flashOn);
      for (let y = 0; y < CELL_H; y++) {
        const bits = y < 7 ? g[y] : 0;
        for (let x = 0; x < CELL_W; x++) {
          // Five wide in a seven-wide cell, one column of padding each side, and bit 4 is
          // the leftmost of the five - not bit 0, which is how the hi-res page is ordered
          // and which drew every character back to front.
          const on = x >= 1 && x <= 5 ? (bits >> (5 - x)) & 1 : 0;
          const lit = inverse ? !on : on;
          const p = ((r * CELL_H + y) * W + c * CELL_W + x) * 4;
          px[p] = lit ? colour[0] : 0;
          px[p + 1] = lit ? colour[1] : 0;
          px[p + 2] = lit ? colour[2] : 0;
          px[p + 3] = 255;
        }
      }
    }
  }
  return out;
}

/** A row as a string, for a harness or a log. */
export function readRow(mem, r, base = 0x400) {
  let s = '';
  for (let c = 0; c < COLS; c++) s += decode(mem[base + OFFSETS[r] + c]).ch;
  return s.replace(/\s+$/, '');
}

/** Clear the page to spaces, which is what the monitor's clear-screen does. */
export function clear(mem, base = 0x400, style = 'normal') {
  const blank = encode(' ', style);
  for (let r = 0; r < ROWS; r++) {
    for (let c = 0; c < COLS; c++) mem[base + OFFSETS[r] + c] = blank;
  }
}
