// The 40x24 text screen.
//
// The text page is 1,024 bytes at `$400` (page 1) or `$800` (page 2), and its rows are
// interleaved the same way the hi-res page's are, one third as deep: row r starts at
// `base + (r & 7) * $80 + (r >> 3) * 40`. Three groups of eight rows, 40 bytes each, with
// eight bytes of "screen holes" after each group that the hardware does not display.
//
// A byte's top two bits are the style and the low six are the character:
//
//     $00-$3F  inverse
//     $40-$7F  flashing
//     $80-$FF  normal
//
// and the character is the low six bits lifted into ASCII - `$00`-`$1F` means `@` to `_`, so
// the obvious `& 0x7F` turns inverse text into control codes. That mistake is already written
// down in `oracle/a2.mjs`, where it made the title read `^S^P^A^C^E` instead of `SPACE`.
//
// **The glyphs are not the machine's.** The Apple II's character shapes live in a ROM on the
// motherboard, not on this disk, so they are not something this repository can measure. What
// is the machine's is everything around them: the 40x24 layout, the 7x8 cell, the interleave,
// the three styles, and which byte is where. The shapes below are a stand-in for the ROM, in
// the same way the phosphor colours in `hgr.js` are a stand-in for a television. If a
// character ROM dump ever turns up, this is the one file that changes.

export const COLS = 40, ROWS = 24;
export const CELL_W = 7, CELL_H = 8;

/** Byte offset within the page of the first byte of row r. */
export function rowOffset(r) {
  return (r & 7) * 0x80 + ((r >> 3) & 3) * 40;
}

const OFFSETS = new Uint16Array(ROWS);
for (let r = 0; r < ROWS; r++) OFFSETS[r] = rowOffset(r);

/**
 * A screen byte, split into what it says and how.
 *
 * The low six bits are the character; `$00`-`$1F` lift to `$40`-`$5F` so that inverse capitals
 * read as capitals.
 */
export function decode(byte) {
  const style = byte >= 0x80 ? 'normal' : (byte >= 0x40 ? 'flash' : 'inverse');
  const low = byte & 0x3F;
  return { style, ch: String.fromCharCode(low < 0x20 ? low + 0x40 : low) };
}

/** The character a byte should be written as, given the current style. */
export function encode(ch, style = 'normal') {
  const c = ch.toUpperCase().charCodeAt(0) & 0x7F;
  const low = (c >= 0x40 && c < 0x60) ? c - 0x40 : c;
  if (style === 'inverse') return low & 0x3F;
  if (style === 'flash') return 0x40 | (low & 0x3F);
  return 0x80 | (c & 0x7F);
}

