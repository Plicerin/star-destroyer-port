// Capture HYPERDRIVE.OBJ0's star tables, after its own setup has filled them.
//
// `$0A63`-`$0E36` is nine hundred bytes of fully unrolled `LDA #imm / STA $08F2,Y /
// STA $092F,Y / INY`, and all it does is fill four tables with constants. Hand-transcribing
// four hundred unrolled stores would be a worse source of error than a capture, and this
// repository already takes captures for exactly this case - MATH's table at `$9800`,
// `HEADING DATA`, the sound parameter blocks. So the port starts from what the machine has
// after the setup runs, and transliterates only the animation above it.
//
// The boundary is not a guess: `$0E23` is `LDY #$00` and the loop under it copies
// `$08F2`-`$092F` into `$09E6` and `$096C` into `$0A23`, sixty-two of each, which is the
// animation taking its working copies. Everything below that is setup.
//
//     node gen_hyperdrive.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { openOracle } from './a2.mjs';
import { openDisk, DISK } from './dsk.mjs';

const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)),
  '../port/src/game/hyperdrive-tables.js');

/** Where the setup stops and the animation starts. */
const SETUP_END = 0x0E23;
/** The four tables, and how many stars there are. */
const TABLES = { dx0: 0x08F2, dy0: 0x096C, dx: 0x09E6, dy: 0x0A23 };
const STARS = 62;                              // CPY #$3E at $0E33

const d = openDisk(DISK);
const HYPER = d.read(d.files.find((x) => x.name === 'HYPERDRIVE.OBJ0'));

const a2 = await openOracle();
let captured;
try {
  await a2.coldStart({ fill: 0x00 });
  for (let i = 0; i < 40; i++) {
    await a2.waitMs(500);
    if ((await a2.screen()).some((r) => r.includes('STARSHIP BATTLE'))) break;
  }
  captured = JSON.parse(await a2.ev(`(() => {
    const cpu = window.M.cpu, wr = window.M.wr, rd = window.M.rd;
    const hyper = ${JSON.stringify([...HYPER.data])};
    for (let i = 0; i < hyper.length; i++) wr(${HYPER.addr} + i, hyper[i]);
    // Run the setup and stop the instant the animation's first instruction is reached.
    const st = cpu.getState(); st.pc = ${HYPER.addr}; st.sp = 0xF8; cpu.setState(st);
    let reached = false, instr = 0;
    cpu.stepCyclesDebug(2000000, () => {
      instr++;
      if (cpu.getPC() === ${SETUP_END}) { reached = true; return true; }
    });
    const region = [];
    for (let a = 0x08F2; a < 0x0A63; a++) region.push(rd(a));
    return JSON.stringify({ reached, instr, region, base: 0x08F2 });
  })()`));
} finally {
  await a2.close();
}

if (!captured.reached) {
  throw new Error(`the setup never reached $${SETUP_END.toString(16)} -`
    + ` ${captured.instr} instructions in, so nothing was captured`);
}
console.log(`setup ran ${captured.instr} instructions and stopped at`
  + ` $${SETUP_END.toString(16).toUpperCase()}`);

const at = (addr) => captured.region.slice(addr - captured.base, addr - captured.base + STARS);
const signed = (b) => (b > 127 ? b - 256 : b);

const dx0 = at(TABLES.dx0), dy0 = at(TABLES.dy0);
console.log(`dx: ${dx0.map(signed).join(' ')}`);
console.log(`dy: ${dy0.map(signed).join(' ')}`);

const rows = (name, bytes) => `export const ${name} = [\n`
  + bytes.map((b, i) => (i % 16 === 0 ? '  ' : '') + String(b).padStart(4)
    + (i === bytes.length - 1 ? '' : ',') + ((i % 16 === 15) ? '\n' : ''))
    .join('').replace(/\n$/, '')
  + '\n];\n';

const text = `// Generated by oracle/gen_hyperdrive.mjs from the running machine. Do not edit.
//
// HYPERDRIVE.OBJ0's star tables, as its own setup leaves them. The setup is $0A63-$0E22,
// nine hundred bytes of unrolled stores and nothing else; this is what they add up to.
//
// ${STARS} stars. \`DX\` and \`DY\` are each star's step, as signed bytes - the velocity rings
// a starfield needs, -1..1 then -2..2 then -3..3 and so on outward. The animation copies
// them into its working pair at $09E6 and $0A23 and adds them to the positions each frame.

/** How many stars the sequence animates. \`CPY #$3E\` at $0E33. */
export const STARS = ${STARS};

/** Where each table lives in the image, for a harness that wants to compare. */
export const AT = ${JSON.stringify(TABLES, null, 2).replace(/"/g, '')};

${rows('DX', dx0)}
${rows('DY', dy0)}`;

fs.writeFileSync(OUT, text);
console.log(`\nwrote ${OUT}`);
