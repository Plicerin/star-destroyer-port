// A listing of STAR DESTROYER.OBJ0, with the addresses it reaches into named.
//
// The same thing probe_renderer.mjs produces for the engine. What makes this one readable
// is that the engine and the display list are already understood, so every reference out
// of the game into $6000-$83FF can be labelled with what it means - `object 3 heading`
// rather than `$8154`. Most of what the game does is poke those addresses, so most lines
// of interest name themselves.
import { openDisk, DISK } from './dsk.mjs';
import { disasm1, traverse, hx } from './disasm6502.mjs';
import fs from 'fs';

const d = openDisk(DISK);
const file = (n) => d.read(d.files.find((x) => x.name === n));
const mem = new Uint8Array(0x10000);
for (const n of ['A2-3D2', 'SV DATA', 'MAIN DATA', 'STAR DESTROYER.OBJ0']) {
  const x = file(n);
  for (let i = 0; i < x.len; i++) mem[x.addr + i] = x.data[i];
}
const obj = file('STAR DESTROYER.OBJ0');
const LO = obj.addr, HI = LO + obj.len;

/** Every display-list address, named by the instruction and field it belongs to. */
const sym = {
  0x6000: 'RENDER', 0x6003: 'RENDER.NOSAVE', 0x6006: 'SIN', 0x6009: 'COS',
  0xFB1E: 'PREAD', 0xC000: 'KBD', 0xC010: 'KBDSTRB', 0xC030: 'SPKR', 0xC061: 'BUTTON0',
  0x8110: 'DISPLAY.PAGE', 0x8112: 'CLEAR.PAGE', 0x8114: 'DRAW.PAGE',
  0x8116: 'XI', 0x8117: 'XI+1', 0x8118: 'YI', 0x8119: 'YI+1', 0x811A: 'ZI', 0x811B: 'ZI+1',
  0x811C: 'P1.pitch', 0x811D: 'B1.bank', 0x811E: 'H1.heading',
  0x81DD: 'SHLD', 0x81F3: 'WARP', 0x8209: 'MSL',
};
const FIELD = ['count', 'x', 'x+1', 'y', 'y+1', 'z', 'z+1', 'pitch', 'bank', 'heading', 'shape', 'shape+1'];
for (let i = 0; i < 24; i++) {
  const base = i < 12 ? 0x8123 + i * 13 : 0x8247 + (i - 12) * 13;
  sym[base] = `OBJ${i}`;
  for (let k = 0; k < 12; k++) sym[base + 1 + k] = `OBJ${i}.${FIELD[k]}`;
}
// The seven 2-D blips, S(1)..S(7) in the author's own names.
for (let i = 0; i < 7; i++) { sym[0x8222 + i * 3] = `BLIP${i + 1}.x`; sym[0x8223 + i * 3] = `BLIP${i + 1}.y`; }

const { starts, calls } = traverse(mem, [LO], { lo: LO, hi: HI });
// Call targets inside the overlay get a label, so the listing reads as routines.
for (const [t, n] of calls) if (t >= LO && t < HI && !sym[t]) sym[t] = `L${hx(t, 4).slice(1)}`;

const out = [
  `; STAR DESTROYER.OBJ0, ${hx(LO, 4)}-${hx(HI - 1, 4)}, ${obj.len} bytes.`,
  '; Generated by oracle/gen_game_listing.mjs. The entry is a JMP into the frame loop.',
  ';',
  '; Addresses in $6000-$83FF are named by what they are in the display list, because',
  '; that is the whole of this binary\'s output: see "The game is in the overlays" and',
  '; "The game loop, traced" in DISK_TRUTH.md.',
  ';',
];
let a = LO;
while (a < HI) {
  if (!starts.has(a)) {
    const run = [];
    while (a < HI && !starts.has(a) && run.length < 16) { run.push(mem[a]); a++; }
    const at = a - run.length;
    out.push(`${hx(at, 4)}  ${(sym[at] ? sym[at] + ':' : '').padEnd(16)}`
      + `.byte ${run.map((v) => hx(v)).join(', ')}`);
    continue;
  }
  const x = disasm1(mem, a, sym);
  out.push(`${hx(a, 4)}  ${(sym[a] ? sym[a] + ':' : '').padEnd(16)}`
    + `${x.bytes.map((v) => v.toString(16).toUpperCase().padStart(2, '0')).join(' ').padEnd(9)}  ${x.text}`);
  a += x.len;
}
fs.mkdirSync('listing', { recursive: true });
fs.writeFileSync('listing/STAR_DESTROYER.asm', out.join('\n') + '\n');
console.log(`wrote listing/STAR_DESTROYER.asm - ${starts.size} instructions`);
