// Extract A2-3D2's four plotting tables into the port, as data with provenance.
//
// $7223-$7622 is 1,024 bytes the engine indexes directly to turn an (x, y) into a screen
// address and a bit mask. The port could compute them - probe_screen2d.mjs establishes
// that within range they are exactly `bit = 140 + 2x` and `row = 95 - y` - but OUTSIDE
// that range they wrap, to real addresses that are the wrong rows, and the original will
// happily plot there. Embedding the tables is exact for all 256 values of each; the
// derived formulas are checked against them in parity_screen.mjs, so the understanding is
// tested rather than merely written down.
import { engineMemory } from './renderer.mjs';
import fs from 'fs';

const { mem } = engineMemory();
const grab = (at) => [...mem.slice(at, at + 256)];
const fmt = (a) => {
  const rows = [];
  for (let i = 0; i < 256; i += 16) rows.push('  ' + a.slice(i, i + 16).map((v) => String(v).padStart(3)).join(', '));
  return rows.join(',' + String.fromCharCode(10));
};

const out = [
  '// Generated by oracle/gen_tables.mjs from A2-3D2 on the original disk. Do not edit.',
  '//',
  '// The four tables the point plotter at $771F indexes, in the engine\'s own order:',
  '//',
  '//   ROW_HI[y] + page   the row\'s address, high byte',
  '//   ROW_LO[y]          the row\'s address, low byte, which the x byte offset is added to',
  '//   X_BYTE[x]          the byte offset within the row',
  '//   X_MASK[x]          a two-bit mask; bit 7 set means the cell straddles a byte boundary',
  '',
  'export const ROW_HI = [', fmt(grab(0x7223)), '];',
  '',
  'export const ROW_LO = [', fmt(grab(0x7323)), '];',
  '',
  'export const X_BYTE = [', fmt(grab(0x7423)), '];',
  '',
  'export const X_MASK = [', fmt(grab(0x7523)), '];',
  '',
].join(String.fromCharCode(10));

fs.mkdirSync('../port/src/a23d2', { recursive: true });
fs.writeFileSync('../port/src/a23d2/tables.js', out);
console.log('wrote port/src/a23d2/tables.js - 4 tables of 256 bytes from $7223-$7622');
